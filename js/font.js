  var cache = {};
  function glyphCanvas(ch, color) {
    var key = ch + '\u0001' + color;
    var c = cache[key];
    if (c) return c;
    var g = glyphs[ch];
    c = document.createElement('canvas');
    c.width = Math.max(1, g.w); c.height = 8;
    var x = c.getContext('2d');
    x.fillStyle = color;
    for (var r = 0; r < g.rows.length; r++) for (var q = 0; q < g.rows[r].length; q++) if (g.rows[r][q] === '#') x.fillRect(q, r, 1, 1);
    cache[key] = c;
    return c;
  }
  function advance(ch) { return ch === ' ' ? 3 : glyphs[ch].w + 1; }

  // parse "{y}Barley{/} hits" into runs. {x} sets a colour from DS.COLORS; {/} resets.
  function runs(str, base) {
    var out = [], col = base, i = 0, buf = '';
    str = String(str);
    while (i < str.length) {
      var ch = str[i];
      if (ch === '{') {
        var j = str.indexOf('}', i);
        if (j > i && j - i <= 3) {
          var code = str.slice(i + 1, j);
          if (buf) { out.push([buf, col]); buf = ''; }
          col = code === '/' ? base : (DS.COLORS[code] || base);
          i = j + 1; continue;
        }
      }
      buf += ch; i++;
    }
    if (buf) out.push([buf, col]);
    return out;
  }
  DS.stripCodes = function (s) { return String(s).replace(/\{[a-z\/]\}/g, ''); };
  DS.textWidth = function (str) {
    var s = DS.stripCodes(str), w = 0;
    for (var i = 0; i < s.length; i++) w += advance(norm(s[i]));
    return Math.max(0, w - 1);
  };
  // draw text; returns width. `limit` (optional) = max visible characters (typewriter)
  DS.text = function (ctx, str, x, y, color, limit) {
    var rr = runs(str, color || DS.COLORS.w), cx = Math.round(x), n = 0;
    y = Math.round(y);
    for (var k = 0; k < rr.length; k++) {
      var s = rr[k][0], col = rr[k][1];
      for (var i = 0; i < s.length; i++) {
        if (limit != null && n >= limit) return cx - x;
        var ch = norm(s[i]);
        if (ch !== ' ') ctx.drawImage(glyphCanvas(ch, col), cx, y);
        cx += advance(ch); n++;
      }
    }
    return cx - x;
  };
  DS.textRight = function (ctx, str, xr, y, color) { return DS.text(ctx, str, xr - DS.textWidth(str), y, color); };
  DS.textCenter = function (ctx, str, xc, y, color) { return DS.text(ctx, str, Math.round(xc - DS.textWidth(str) / 2), y, color); };
  DS.textLen = function (str) { return DS.stripCodes(str).length; };
  // word-wrap keeping colour codes; returns array of lines (codes carried across lines)
  DS.wrap = function (str, maxW) {
    var out = [];
    String(str).split('\n').forEach(function (para) {
      var words = para.split(' '), line = '', open = '';
      words.forEach(function (w) {
        var test = line ? line + ' ' + w : w;
        if (DS.textWidth(test) > maxW && line) {
          out.push(line);
          line = open + w;
        } else line = test;
        var m = w.match(/\{([a-z\/])\}/g);
        if (m) { var last = m[m.length - 1]; open = last === '{/}' ? '' : last; }
      });
      out.push(line);
    });
    return out;
  };
