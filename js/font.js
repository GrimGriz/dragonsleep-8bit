  var ALIAS = { '‘': "'", '’': "'", '“': '"', '”': '"', '–': '-', '×': 'x' };
  var glyphs = {};
  Object.keys(G).forEach(function (ch) {
    var rows = G[ch].split('|');
    var w = 0; rows.forEach(function (r) { if (r.length > w) w = r.length; });
    glyphs[ch] = { rows: rows, w: w };
  });
  function norm(ch) {
    if (glyphs[ch]) return ch;
    if (ALIAS[ch]) return ALIAS[ch];
    var n = ch.normalize ? ch.normalize('NFD').replace(/[̀-ͯ]/g, '') : ch;
    if (glyphs[n]) return n;
    return '?';
  }
