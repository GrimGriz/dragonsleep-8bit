"""THE WORLD BAKE (10-20, the world map seat; RULED his "go on all leans"): the second game's world map from his realm hex map. His newest EXPORT
(play-records/realm-hexmap-<UTC>.json, or a path given) is opened in tools/hexmap.html headless -- the tool's own engine, so the heights, the wet floors
and the ground are the world look he sees -- and HEXMAP.bake() is written to deep16/data/world.js (D16.WORLD). Then python tools/deep16-build.py stamps it.
A hex he has not painted takes the paint of the regions beside it (THE FILL, tools/hexmap.js, 10-21: RULED his "all the unpainted hexes should take on
paint of adjacent regions"; corridor v3's guess before). He paints and EXPORTs; this bakes. Run from PowerShell (the benches' headless browser):
python tools/world-build.py [export.json]"""
import glob, json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, 'dev'))
import bench16


def newest_export():
    # (his EXPORTs are named by their UTC time; the shared checkout's play-records when run in a worktree, which has none of its own)
    dirs = [os.path.join(ROOT, 'play-records')]
    m = re.search(r'^(.*)[\\/]\.claude[\\/]worktrees[\\/][^\\/]+$', ROOT)
    if m: dirs.append(os.path.join(m.group(1), 'play-records'))
    files = [f for d in dirs for f in glob.glob(os.path.join(d, 'realm-hexmap-*.json')) if os.path.getsize(f) > 0]
    return max(files, key=lambda f: os.path.basename(f)) if files else None


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else newest_export()
    if not src: print('FAIL no hex map EXPORT found (play-records/realm-hexmap-<UTC>.json)'); return 1
    o = json.load(open(src, encoding='utf-8')); o.pop('exported', None); o.pop('about', None)
    key = 'realm-hexmap-v1' if o.get('v') == 1 else 'realm-hexmap-v2'
    # served (not file://), from the folder that holds TarlynsPit, as he opens it (its underlays)
    top = ROOT
    while not os.path.isdir(os.path.join(top, 'TarlynsPit')) and os.path.dirname(top) != top: top = os.path.dirname(top)
    import socket, subprocess, time
    s = socket.socket(); s.bind(('127.0.0.1', 0)); port = s.getsockname()[1]; s.close()
    srv = subprocess.Popen([sys.executable, '-m', 'http.server', str(port), '--bind', '127.0.0.1'], cwd=top, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    page = 'http://127.0.0.1:%d/%s' % (port, os.path.relpath(os.path.join(ROOT, 'tools', 'hexmap.html'), top).replace('\\', '/'))
    from playwright.sync_api import sync_playwright
    try:
        time.sleep(1.0)
        with sync_playwright() as pw:
            b = pw.chromium.launch(executable_path=bench16.browser(), headless=True, args=bench16.EXTRA)
            pg = b.new_page(viewport={'width': 1200, 'height': 800}); errs = []
            pg.on('pageerror', lambda e: errs.append(str(e)))
            pg.goto(page); pg.wait_for_timeout(200)
            pg.evaluate('([k, t]) => { localStorage.clear(); localStorage.setItem(k, t); }', [key, json.dumps(o)])
            pg.reload(); pg.wait_for_function('window.HEXMAP && window.HEXMAP.S()')
            W = pg.evaluate('HEXMAP.bake()')
            b.close()
    finally:
        srv.terminate()
    if errs: print('FAIL the tool threw: ' + '; '.join(errs[:3])); return 1
    W['from'] = os.path.basename(src)
    # the tiles (the top-down view's half-mile ground) go in a file of their own, loaded only when that view opens (deep16/js/overworld.js): not on every DEEP16 page
    import hashlib
    T = W.pop('tiles', None)
    if T:
        ttext = ("/* THE WORLD'S TILES -- generated by tools/world-build.py from " + W['from'] + ": every half mile its ground, its height's band and its road, for\n"
                 "   the top-down view (deep16/js/overworld.js loads this when it opens). Never edit this. */\n"
                 "'use strict';\n(window.D16 = window.D16 || {}).WORLD_TILES = " + json.dumps(T, separators=(',', ':')) + ";\n")
        W['tilesV'] = hashlib.sha1(ttext.encode('utf-8')).hexdigest()[:10]
        tout = os.path.join(ROOT, 'deep16', 'data', 'world-tiles.js')
        if not os.path.exists(tout) or open(tout, encoding='utf-8').read() != ttext:
            with open(tout, 'w', encoding='utf-8', newline='\n') as f: f.write(ttext)
        print('wrote deep16/data/world-tiles.js: %d x %d half-mile tiles, %d KB' % (T['w'], T['h'], len(ttext) // 1024))
    # THE LOOK (10-21, his "it seems to me the second image could look more like the first with a clever paintjob"): every half mile lit as the finest
    # view lights it, one picture; deep16/js/world.js lays it on each hex's top, loaded when THE WORLD opens (not on every DEEP16 page)
    Lk = W.pop('look', None)
    if Lk:
        import base64
        png = base64.b64decode(Lk.pop('png').split(',', 1)[1])
        Lk['v'] = hashlib.sha1(png).hexdigest()[:10]; W['look'] = Lk
        lout = os.path.join(ROOT, 'deep16', 'data', 'world-look.png')
        if not os.path.exists(lout) or open(lout, 'rb').read() != png:
            with open(lout, 'wb') as f: f.write(png)
            print('wrote deep16/data/world-look.png: %d x %d, a half mile a pixel, %d KB' % (Lk['w'], Lk['h'], len(png) // 1024))
    out = os.path.join(ROOT, 'deep16', 'data', 'world.js')
    text = ("/* THE WORLD -- generated by tools/world-build.py from his realm hex map EXPORT " + W['from'] + " (tools/hexmap.html's own engine): the second game's\n"
            "   world map, the 5-mile hexes walked as one token (deep16/js/world.js, deep16/?world). Paint in the tool, EXPORT, run the build -- never edit this. */\n"
            "'use strict';\n(window.D16 = window.D16 || {}).WORLD = " + json.dumps(W, separators=(',', ':')) + ";\n")
    old = open(out, encoding='utf-8').read() if os.path.exists(out) else None
    if old is None or re.sub(r'"baked":"[^"]*"', '', old) != re.sub(r'"baked":"[^"]*"', '', text):
        with open(out, 'w', encoding='utf-8', newline='\n') as f: f.write(text)
        print('wrote deep16/data/world.js: %d hexes, %d places, %d roads and rivers, from %s' % (len(W['hexes']), len(W['sites']), len(W['paths']), W['from']))
    else: print('deep16/data/world.js unchanged (%s)' % W['from'])
    print('the fill: %d hexes not painted took the paint beside them, %d with only a lake, a cut or a town of his in a corner took it as their ground (his place their second); guessed %d'
          % (W.get('filled', 0), W.get('parted', 0), W.get('guessed', 0)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
