"""DEEP16 pipeline 2 (generated art): the road's props -- the art desk's ART-58, ART-59 and ART-60 (one delivery, 2026-10-14) ->
lamptower_p1, rubble_p1 and goblincamp_p1.

    python tools/roadprops-sheet.py          (all three; `check` also writes dev/visions/roadprops-check.png, the frames at 4x)

Sources (gitignored, deep16/_src/): lamptower_p1/ART-58_PAGE-1.png, rubble_p1/ART-59_PAGE-1.png, goblincamp_p1/ART-60_PAGE-1.png -- the art
desk's FINAL SHEETS (Griz's ChatGPT project, 2026-10-14; its papers in _src/art-desk/received-2026-10-14-ROADPROPS/), asked in
deep16-art-wanted.md §8 (13a01d6) for the dwarven road (the party-token map lane §4.6, §7). One cutter for the one delivery, as
tools/wetprops-sheet.py cuts the Wet's three; the assignments' three cutter names are this file.

Each page is drawings on a flat navy with lettering beside them (row names, frame numbers). A drawing is every blob whose middle falls in
its region (REGIONS, read off a probe of the page): a scatter's chips and a fire's sparks and smoke are blobs of their own. Lettering is
dropped by its boxes (TEXT). Each drawing is boxed down to game size, snapped to deep16/palette.json and outlined (tools/gsprops-sheet.py
game(), tools/pixelate.py), as the chest and the cots were.

Scale (full height, RULED 10-14 for the props: 8 px a foot; the floor diamond 64 x 32, js/iso.js):
  - the tower: Lit 1 from its plinth's foot to the ring on the cage's roof is 96 px (12 ft, the assignment's). The page draws Dark 1% bigger
    than Lit (186 x 460 against 184 x 455); it is cut at its own size so it stands as tall as Lit.
  - rubble: one scale for the page, Scatter A's spread 60 px across (its diamond's width, short of the corners). The heaps then come out 37
    to 40 px tall on one diamond: waist high (3 ft, 24 px above the floor's middle) as asked.
  - the camp: one scale for the page, Tent A across its two diamonds (96 px). GPT drew Tent B smaller than asked: at the page's scale it
    stands on one diamond, its ridge about 4 ft (as asked). The fire's stone ring is then about 31 px across, the bones about 50.

Rows that play: the tower's Lit (four flame frames) and the camp's Fire (six). Each frame is laid on frame 1 by its foot (the plinth's, the
stone ring's: the middle across of its lowest rows, and the lowest row), so the stone stands still while the flame moves; then, where frame
1 is not warm (STILL), frame 1's own pixels are kept, so the stone, the cage and the ring do not shimmer from one frame's resampling to the
next -- only the flame, its glow and the smoke change. The Dark tower is laid on Lit 1 the same way and kept whole (its glass is cold).

Anchors (ax, ay), one a sheet, every drawing laid so its own anchor falls there (the cots' way, tools/gsprops-sheet.py cot()):
  - standing things (the tower, the heaps, Tent B, the fire): the middle of the square, the drawing's middle across and a quarter of its
    width up from its lowest point (the footprint's front corner); the fire's by its ring, the widest part.
  - Tent A: the middle of its two squares (the same rule over its 96 px): it lies along the grid's y, its ridge from the upper right down to
    the lower left, its open end to the lower left (+y). js/circles.js stands it on its back square and the one in front (gx, gy + 1).
  - flat things (Scatter A and B, the bones): the middle of the drawing, which lies on the middle of its diamond.
"""
