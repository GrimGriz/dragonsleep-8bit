import importlib.util
import numpy as np
from PIL import Image
from scipy import ndimage

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path); mod = importlib.util.module_from_spec(spec); spec.loader.exec_module(mod)
    return mod
GS = _load('gsprops', os.path.join(ROOT, 'tools', 'gsprops-sheet.py'))      # game(), write(), src(): the chest's and the cots'
SR = GS.SR
pix = GS.pix

GS.FPS.update({'lit': 6, 'dark': 1, 'scatterA': 1, 'scatterB': 1, 'heapA': 1, 'heapB': 1, 'heapC': 1,
               'tentA': 1, 'tentB': 1, 'bones': 1, 'fire': 8})
SRC = 'generated by the art desk (Griz\'s ChatGPT project, 2026-10-14: %s, FINAL SHEETS), cut by tools/roadprops-sheet.py'

PAGES = {
    'tower': dict(file=os.path.join('lamptower_p1', 'ART-58_PAGE-1.png'),
                  text=[(30, 240, 100, 290), (30, 722, 135, 770), (300, 480, 1330, 516)],          # Lit, Dark, the numbers 1-4
                  regions=[('lit1', (200, 0, 500, 480)), ('lit2', (520, 0, 820, 480)), ('lit3', (840, 0, 1140, 480)),
                           ('lit4', (1160, 0, 1460, 480)), ('dark', (150, 500, 480, 1010))]),
    'rubble': dict(file=os.path.join('rubble_p1', 'ART-59_PAGE-1.png'),
                   text=[(340, 370, 540, 410), (980, 370, 1180, 410), (190, 820, 330, 865), (685, 820, 825, 865), (1180, 820, 1320, 865)],
                   regions=[('scatterA', (150, 100, 740, 372)), ('scatterB', (760, 100, 1400, 372)), ('heapA', (20, 420, 500, 822)),
                            ('heapB', (500, 420, 970, 822)), ('heapC', (970, 420, 1530, 822))]),
    'camp': dict(file=os.path.join('goblincamp_p1', 'ART-60_PAGE-1.png'),
                 text=[(195, 486, 330, 524), (845, 486, 975, 524), (1290, 486, 1410, 524), (55, 540, 135, 580), (100, 888, 1420, 932)],
                 regions=[('tentA', (0, 0, 700, 486)), ('tentB', (700, 60, 1150, 486)), ('bones', (1150, 250, 1536, 486))] +
                         [('fire%d' % (i + 1), (15 + 249 * i, 580, 265 + 249 * i, 888)) for i in range(6)]),
}
H_TOWER = 96.0          # Lit 1, the plinth's foot to the ring
W_SCATTER = 60.0        # Scatter A's spread
W_TENTA = 96.0          # Tent A across its two diamonds


def drawings(page):
    """the page's drawings: {name: (sheet-size RGBA array, (w, h) of its figure on the sheet)}"""
    P = PAGES[page]
    a = np.asarray(Image.open(GS.src(P['file'])).convert('RGB')).astype(np.int32)
    m = SR.figure_mask(a)
    SR.drop_text(m, P['text'])
    lab, n = ndimage.label(m, structure=np.ones((3, 3)))
    cms = ndimage.center_of_mass(m, lab, range(1, n + 1))
    out = {}
    for name, (x0, y0, x1, y1) in P['regions']:
        ids = [i + 1 for i, (cy, cx) in enumerate(cms) if x0 <= cx < x1 and y0 <= cy < y1]
        keep = np.isin(lab, ids)
        im, box = SR.rgba_crop(a, keep)
        ys, xs = np.where(keep)
        out[name] = (np.asarray(im), (xs.max() - xs.min() + 1, ys.max() - ys.min() + 1))
        print('  %s %-9s %d blobs, %d x %d on the page' % (page, name, len(ids), out[name][1][0], out[name][1][1]))
    return out


def foot(c):
    """a game-size frame's foot: the middle across of its lowest 3 rows, and its lowest row"""
    al = c[..., 3] > 0
    ys = np.where(al.any(1))[0]
    xs = np.where(al[ys[-1] - 2:ys[-1] + 1].any(0))[0]
    return (xs.min() + xs.max()) / 2.0, ys[-1]


def stand_anchor(c):
    """the middle of the square a standing thing stands on: its middle across, a quarter of its width up from its lowest point"""
    al = c[..., 3] > 0
    ys, xs = np.where(al)
    return (xs.min() + xs.max()) / 2.0, ys.max() - (xs.max() - xs.min() + 1) / 4.0


def flat_anchor(c):
    al = c[..., 3] > 0
    ys, xs = np.where(al)
    return (xs.min() + xs.max()) / 2.0, (ys.min() + ys.max()) / 2.0


def warm(c):
    """flame, glow and smoke over the stone: warm (red well over blue) or a pale grey-blue wisp -- the parts a lit row moves"""
    r, g, b, al = [c[..., i].astype(np.int32) for i in range(4)]
    return (al > 0) & (r > b + 50) & (r > 110)


def on_foot(frames):
    """frames: [game-size RGBA] -> the same, each on one cell, laid on frame 1 by its foot; and frame 1's (fx, fy) in the cell"""
    feet = [foot(c) for c in frames]
    offs = [(int(round(feet[0][0] - fx)), int(feet[0][1] - fy)) for fx, fy in feet]
    x0 = min(dx for dx, _ in offs); y0 = min(dy for _, dy in offs)
    x1 = max(dx + c.shape[1] for (dx, _), c in zip(offs, frames)); y1 = max(dy + c.shape[0] for (_, dy), c in zip(offs, frames))
    out = []
    for (dx, dy), c in zip(offs, frames):
        cell = np.zeros((y1 - y0, x1 - x0, 4), np.uint8)
        cell[dy - y0:dy - y0 + c.shape[0], dx - x0:dx - x0 + c.shape[1]] = c
        out.append(cell)
    return out, (feet[0][0] - x0, feet[0][1] - y0)


def still(cells, keep_above=None):
    """a lit row's frames 2..n: frame 1's own pixels wherever neither frame is warm (the stone does not shimmer); `keep_above`: rows above
    it (the smoke's) are the frame's own, whatever they are"""
    base = cells[0]
    out = [base]
    for c in cells[1:]:
        moving = ndimage.binary_dilation(warm(base) | warm(c), iterations=1)
        if keep_above is not None:
            moving[:keep_above] = True
        f = base.copy()
        f[moving] = c[moving]
        out.append(f)
    return out


def one_cell(items, pad=2):
    """items: [(row, [cells], (ax, ay))] -> rows on one cell size, every drawing's anchor on one (ax, ay)"""
    AX = max(int(round(ax)) for _, _, (ax, ay) in items) + pad
    AY = max(int(round(ay)) for _, _, (ax, ay) in items) + pad
    FW = max(AX - int(round(ax)) + cs[0].shape[1] for _, cs, (ax, ay) in items) + pad
    FH = max(AY - int(round(ay)) + cs[0].shape[0] for _, cs, (ax, ay) in items) + pad
    rows = []
    for row, cs, (ax, ay) in items:
        ox, oy = AX - int(round(ax)), AY - int(round(ay))
        cells = []
        for c in cs:
            cell = np.zeros((FH, FW, 4), np.uint8)
            cell[oy:oy + c.shape[0], ox:ox + c.shape[1]] = c
            cells.append(cell)
        rows.append((row, cells))
    return rows, FW, FH, AX, AY


def tower():
    d = drawings('tower')
    k = d['lit1'][1][1] / H_TOWER
    lit = [GS.game(d['lit%d' % (i + 1)][0], k) for i in range(4)]
    dark = GS.game(d['dark'][0], d['dark'][1][1] / H_TOWER)          # its own size: as tall as Lit 1
    cells, (fx, fy) = on_foot(lit + [dark])
    lit = still(cells[:4])
    ax, ay = stand_anchor(lit[0])
    rows, fw, fh, ax, ay = one_cell([('lit', lit, (ax, ay)), ('dark', [cells[4]], (ax, ay))])
    print('  tower k %.2f: %d px to the ring' % (k, (lit[0][..., 3] > 0).any(1).sum()))
    note = ('the lamp tower at a waystation on the dwarven road (tools/roadprops-sheet.py, the art desk\'s ART-58): a plinth of dwarf-cut '
            'stone on one diamond, a banded shaft, a capital and an iron lamp cage, 12 ft to the ring on its roof. lit, four frames of the '
            'flame (the stone the same in all four); dark, the lamp gone out. (ax, ay) is the middle of the square it stands on. Its light '
            'is the map\'s own `lights` entry (js/circles.js draws it where a map\'s `tower` stands).')
    return GS.write('lamptower_p1', rows, fw, fh, ax, ay, note, SRC % 'ART-58')


def rubble():
    d = drawings('rubble')
    k = d['scatterA'][1][0] / W_SCATTER
    items = []
    for row in ('scatterA', 'scatterB', 'heapA', 'heapB', 'heapC'):
        c = GS.game(d[row][0], k)
        items.append((row, [c], flat_anchor(c) if row.startswith('scatter') else stand_anchor(c)))
        al = c[..., 3] > 0
        print('  rubble %s %d x %d' % (row, al.any(0).sum(), al.any(1).sum()))
    rows, fw, fh, ax, ay = one_cell(items)
    note = ('the road\'s rubble (tools/roadprops-sheet.py, the art desk\'s ART-59): broken dwarf-cut stone and cave rock. scatterA, '
            'scatterB: chips and grit spread low over one diamond, ankle high -- a map\'s rough ground (`r`) where a wall or the road has been '
            'broken through (a map\'s `rubble`, js/circles.js); heapA, heapB, heapC: waist-high piles on one diamond, standing in the way '
            '(half cover, as a stalagmite; a map\'s `heaps`). (ax, ay) is the middle of the square: a heap\'s its footprint\'s, a '
            'scatter\'s its own middle.')
    return GS.write('rubble_p1', rows, fw, fh, ax, ay, note, SRC % 'ART-59')


def camp():
    d = drawings('camp')
    k = d['tentA'][1][0] / W_TENTA
    items = []
    for row in ('tentA', 'tentB', 'bones'):
        c = GS.game(d[row][0], k)
        items.append((row, [c], flat_anchor(c) if row == 'bones' else stand_anchor(c)))
        al = c[..., 3] > 0
        print('  camp %s %d x %d' % (row, al.any(0).sum(), al.any(1).sum()))
    fire = [GS.game(d['fire%d' % (i + 1)][0], k) for i in range(6)]
    cells, (fx, fy) = on_foot(fire)
    ring = cells[0][..., 3] > 0
    rs = np.where(ring.any(1))[0]
    fire = still(cells, keep_above=int(rs[-1] - (rs[-1] - rs[0]) * 0.45))   # the flames and the smoke over the ring: each frame's own
    items.append(('fire', fire, stand_anchor(cells[0])))
    print('  camp fire %d x %d' % (ring.any(0).sum(), ring.any(1).sum()))
    rows, fw, fh, ax, ay = one_cell(items)
    note = ('the goblin camp (tools/roadprops-sheet.py, the art desk\'s ART-60): tentA, a lean-to of stitched hides over lashed poles on two '
            'diamonds along the grid\'s y, its open end to the lower left (+y), (ax, ay) the middle of its two squares; tentB, a smaller '
            'sagging hide tent on one diamond, its flap to the lower right (+x); bones, a low heap of gnawed bones and a skull, floor; fire, a '
            'campfire in a ring of stones, six frames looping (the ring the same in all six). js/circles.js stands them where a map\'s `camp` '
            'names them; the fire\'s light is the map\'s `lights` entry.')
    return GS.write('goblincamp_p1', rows, fw, fh, ax, ay, note, SRC % 'ART-60')


def main():
    sheets = [tower(), rubble(), camp()]
    if 'check' in sys.argv[1:]:
        h = sum(s.shape[0] for s in sheets) + 16
        w = max(s.shape[1] for s in sheets)
        canvas = Image.new('RGBA', (w, h), (40, 44, 60, 255))
        y = 0
        for s in sheets:
            canvas.alpha_composite(Image.fromarray(s, 'RGBA'), (0, y)); y += s.shape[0] + 8
        out = os.path.join(ROOT, 'dev', 'visions', 'roadprops-check.png')
        os.makedirs(os.path.dirname(out), exist_ok=True)
        canvas.resize((w * 4, h * 4), Image.NEAREST).save(out)
        print('check:', out)


if __name__ == '__main__':
    main()
